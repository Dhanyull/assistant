PQS.spriteBounds = function (name) {
  const rows = (function(r){ return typeof r === "string" ? r.trim().split("\n").map((l)=>l.trim()) : r; })(PQS.SPRITES[name]);
  if (!rows) return null;
  let minX = 99, minY = 99, maxX = 0, maxY = 0;
  for (let y = 0; y < rows.length; y++) {
    const line = rows[y];
    for (let x = 0; x < line.length; x++) {
      if (PQS.PAL[line[x]]) {
        if (x < minX) minX = x;
        if (y < minY) minY = y;
        if (x > maxX) maxX = x;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (minX === 99) return null;
  return { minX, minY, w: maxX - minX + 1, h: maxY - minY + 1, rows };
};

PQS.drawSpriteFit = function (ctx, name, x, y, box, pad) {
  pad = pad == null ? 1 : pad;
  const b = PQS.spriteBounds(name);
  if (!b) return;
  const scale = Math.max(1, Math.floor(Math.min((box - pad * 2) / b.w, (box - pad * 2) / b.h)));
  const dw = b.w * scale, dh = b.h * scale;
  const dx = x + Math.floor((box - dw) / 2);
  const dy = y + Math.floor((box - dh) / 2);
  const cropped = b.rows.slice(b.minY, b.minY + b.h).map((r) => r.slice(b.minX, b.minX + b.w));
  PQS.drawPixels(ctx, cropped, dx, dy, scale);
};

PQS.paintCrest = function (canvas) {
  const ctx = canvas.getContext("2d");
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  ctx.imageSmoothingEnabled = false;
  PQS.drawSpriteFit(ctx, "crest", 0, 0, canvas.width, 2);
};
