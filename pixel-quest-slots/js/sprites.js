const _cache = new Map();

function parseSprite(rows) {
  if (typeof rows === "string") rows = rows.trim().split("\n").map((l) => l.trim());
  return rows;
}

PQS.drawPixels = function (ctx, rows, x, y, scale, pal) {
  pal = pal || PQS.PAL;
  rows = parseSprite(rows);
  const s = scale || 1;
  for (let ry = 0; ry < rows.length; ry++) {
    const line = rows[ry];
    for (let rx = 0; rx < line.length; rx++) {
      const col = pal[line[rx]];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(x + rx * s, y + ry * s, s, s);
    }
  }
};

PQS.spriteSize = function (name) {
  const rows = parseSprite(PQS.SPRITES[name]);
  return { w: rows[0].length, h: rows.length };
};

PQS.spriteCanvas = function (name, scale) {
  scale = scale || 3;
  const key = name + "@" + scale;
  if (_cache.has(key)) return _cache.get(key);
  const rows = parseSprite(PQS.SPRITES[name]);
  if (!rows) return null;
  const w = rows[0].length, h = rows.length;
  const c = document.createElement("canvas");
  c.width = w * scale;
  c.height = h * scale;
  const ctx = c.getContext("2d");
  ctx.imageSmoothingEnabled = false;
  PQS.drawPixels(ctx, rows, 0, 0, scale);
  _cache.set(key, c);
  return c;
};

PQS.drawSprite = function (ctx, name, x, y, scale) {
  const spr = PQS.spriteCanvas(name, scale || 3);
  if (spr) ctx.drawImage(spr, x, y);
};

